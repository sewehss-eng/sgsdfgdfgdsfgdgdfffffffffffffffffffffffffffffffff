def detect_region(name: str) -> tuple[int, str] | None:
    text = name.strip().casefold().replace("ё", "е")
    # Число само по себе либо число с явным словом «регион»/«рег.».
    patterns = (
        r"^0?(\d{1,2})$",
        r"(?<!\w)0?(\d{1,2})\s*[-–—]?\s*рег(?:ион(?:а)?|\.)?(?!\w)",
        r"(?<!\w)рег(?:ион(?:а)?|\.)?\s*[-–—№:]?\s*0?(\d{1,2})(?!\d)",
        r"^0?(\d{1,2})\s*[-–—.)]\s*[^\d\W]",
    )
    for pattern in patterns:
        match = re.search(pattern, text)
        if match and int(match[1]) in REGIONS:
            code = int(match[1])
            return code, REGIONS[code]
    # Полное имя или имя внутри скобок; не ищем «Москва» как подстроку
    # в «Московская область» и не принимаем название предмета за регион.
    normalized = text.removeprefix("г. ")
    for code, title in REGIONS.items():
        title = title.casefold().replace("ё", "е")
        if normalized == title or f"({title})" in normalized:
            return code, REGIONS[code]
    return None


async def resolve_region(
    drive: DriveService, item_id: str, category_root: str | None = None,
) -> tuple[int, str] | None:
    """Ближайший регион в цепочке родителей. Циклы и длинные пути ограничены."""
    seen: set[str] = set()
    current = item_id
    for _ in range(32):
        if current in seen:
            break
        seen.add(current)
        meta = await drive.get_item(current, with_parents=True)
        region = detect_region(meta.get("name", ""))
        if region:
            return region
        if current == category_root:
            break
        parents = meta.get("parents") or []
        if not parents:
            break
        current = parents[0]
    return None


def region_values(extra: dict[str, str], region: tuple[int, str]) -> dict[str, str]:
    code, title = region
    values = dict(extra)
    for key in ("регион", "region", "region_name", "название_региона"):
        values[key] = title
    for key in ("код_региона", "номер_региона", "region_code", "region_number"):
        values[key] = str(code)
    return values


def correct_region_label(text: str, region: tuple[int, str]) -> str:
    """Совместимость со старыми шаблонами с буквально вписанным регионом."""
    code, title = region
    # Поддерживаем скобки в названиях, например «Саха (Якутия)».
    return re.sub(
        r"(?<!\w)\d{1,3}\s+регион(?:\s*\((?:[^()\n]|\([^()\n]*\))*\))?(?!\w)",
        lambda _: f"{code} регион ({title})",
        text,
        flags=re.IGNORECASE,
    )
